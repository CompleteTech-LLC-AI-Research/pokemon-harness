#!/usr/bin/env python3
"""Install the pinned PyBoy source runtime into the active environment.

The normal harness distribution already bundles this source tree.  This
bootstrap is for the two explicit runtime modes used by development and
performance testing:

* ``source`` (default): install the harness distribution and its Python sources;
* ``cython``: build the same sources with PyBoy's Cython extensions.

Both modes use the checked-in source snapshot.  No network VCS checkout,
``PYTHONPATH`` override, or machine-specific path is involved.

Native builds use a temporary source-only copy, never generated C or build
outputs from the vendor checkout. After staging, native subprocess budgets are
install-timeout + 2 * check-timeout (660s by default), plus bounded process-tree
cleanup on timeout; copying and cleanup are not an end-to-end deadline.
"""


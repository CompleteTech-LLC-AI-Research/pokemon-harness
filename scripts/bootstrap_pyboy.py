# Audited against the pinned setup.py, pyproject.toml and MANIFEST.in: setup
# reads package sources; metadata reads README/license; MANIFEST adds the
# built-in pyboy/default_rom.gb. Keep the complete package, including C headers
# and all .pxd/.pxi dependencies, rather than selecting individual extensions.
NATIVE_BUILD_ROOT_FILES = (
    "setup.py", "pyproject.toml", "MANIFEST.in", "README.md", "LICENSE.md",
    "POKERED_HARNESS_PYBOY_REVISION",
)
NATIVE_BUILD_OUTPUT_DIRS = {"build", "dist", "cython_debug", "__pycache__"}
NATIVE_BUILD_OUTPUT_SUFFIXES = {".so", ".pyd", ".dll", ".o", ".obj", ".pyc", ".pyo"}


def _native_build_input(path: Path) -> bool:
    """Exclude proven outputs; preserve unknown C and non-build runtime data."""
    if path.name in NATIVE_BUILD_OUTPUT_DIRS or path.name.endswith(".egg-info"):
        return False
    if path.suffix.lower() in NATIVE_BUILD_OUTPUT_SUFFIXES:
        return False
    if path.is_symlink():
        raise ValueError(f"symlink is not allowed in native build inputs: {path}")
    if path.is_dir():
        return True
    if not path.is_file():
        raise ValueError(f"native build input is not a regular file: {path}")
    if path.suffix.lower() in {".c", ".cpp", ".h", ".hpp"}:
        with path.open("rb") as stream:
            generated = stream.read(128).lstrip().startswith(b"/* Generated by Cython ")
        if generated:
            stems = [path.stem]
            if path.suffix.lower() in {".h", ".hpp"} and path.stem.endswith("_api"):
                stems.append(path.stem[:-4])
            sources = [path.with_name(stem + ext) for stem in stems for ext in (".py", ".pyx")]
            if not any(source.is_file() and not source.is_symlink() for source in sources):
                raise ValueError(f"generated Cython output has no regeneration source: {path}")
            return False
    return True


@contextmanager
def _native_build_source():
    """Stage all pinned packaging inputs without mutating the vendor checkout."""
    with tempfile.TemporaryDirectory(prefix="pokered-pyboy-native-") as directory:
        staged = Path(directory) / "source"
        staged.mkdir()
        for name in NATIVE_BUILD_ROOT_FILES:
            source = PYBOY_SOURCE / name
            if not _native_build_input(source) or not source.is_file():
                raise ValueError(f"required native packaging file is missing: {source}")
            shutil.copy2(source, staged / name)
        package = PYBOY_SOURCE / "pyboy"
        if not _native_build_input(package) or not package.is_dir():
            raise ValueError(f"native package directory is missing: {package}")

        def ignore(directory, names):
            return [name for name in names if not _native_build_input(Path(directory) / name)]

        shutil.copytree(package, staged / "pyboy", ignore=ignore)
        yield staged


def _editable_root(distribution: importlib.metadata.Distribution) -> Path | None:
    """Read an installed editable's origin, including Windows file URLs."""
    try:
        direct = json.loads(distribution.read_text("direct_url.json") or "{}")
        url = urlsplit(direct.get("url", ""))
        if not direct.get("dir_info", {}).get("editable") or url.scheme != "file":
            return None
        if url.netloc not in {"", "localhost"}:
            return None
        return Path(url2pathname(url.path)).resolve()
    except (ValueError, TypeError, AttributeError):
        return None


def _owned_origin(
    distribution: importlib.metadata.Distribution,
    module: str,
    origin: str,
    *,
    allow_editable: bool,
) -> bool:
    path = Path(origin).resolve()
    # Wheel RECORD paths establish actual ownership; hashes also detect a second
    # distribution overwriting the same import path with different bytes.
    for entry in distribution.files or ():
        if Path(distribution.locate_file(entry)).resolve() != path:
            continue
        if entry.hash is None:
            return False
        try:
            digest = hashlib.new(entry.hash.mode, path.read_bytes()).digest()
        except (OSError, ValueError):
            return False
        return base64.urlsafe_b64encode(digest).rstrip(b"=").decode() == entry.hash.value
    root = _editable_root(distribution) if allow_editable else None
    if root is None:
        return False
    parts = module.split(".")
    package_root = (
        root / "vendor" / "pyboy-src" / "pyboy"
        if parts[0] == "pyboy"
        else root / "src" / "pokered_harness"
    )
    module_path = package_root.joinpath(*parts[1:])
    return path in {
        module_path.with_suffix(".py").resolve(),
        (module_path / "__init__.py").resolve(),
    }


def _verify_ownership(mode: str, origins: dict[str, str]) -> str:
    try:
        harness = importlib.metadata.distribution("pokered-harness")
    except importlib.metadata.PackageNotFoundError as exc:
        raise SystemExit("PyBoy contract failed: pokered-harness is not installed") from exc
    try:
        native = importlib.metadata.distribution("pyboy")
    except importlib.metadata.PackageNotFoundError:
        native = None
    if mode == "source" and native is not None:
        raise SystemExit(
            "PyBoy source contract failed: standalone pyboy distribution is installed; "
            "use a clean source environment containing only pokered-harness"
        )
    if mode == "cython" and native is None:
        raise SystemExit("PyBoy cython contract failed: the built fork is not installed")
    for module, origin in origins.items():
        owner = native if mode == "cython" and module.startswith("pyboy") else harness
        if not _owned_origin(owner, module, origin, allow_editable=owner is harness):
            raise SystemExit(
                f"PyBoy {mode} contract failed: {module} at {origin} is not owned "
                f"by the selected {owner.metadata['Name']} installation"
            )
    return "pyboy" if mode == "cython" else "pokered-harness"


def _validate_source() -> None:
    if not PYBOY_SOURCE.is_dir():
        raise SystemExit(f"vendored PyBoy source is missing: {PYBOY_SOURCE}")
    try:
        revision = REVISION_FILE.read_text(encoding="ascii").strip()
    except OSError as exc:
        raise SystemExit(f"cannot read PyBoy revision marker: {REVISION_FILE}: {exc}") from exc
    if revision != EXPECTED_REVISION:
        raise SystemExit(
            "vendored PyBoy revision mismatch: "
            f"expected {EXPECTED_REVISION}, got {revision or '<empty>'}"
        )


def _module_kind(path: str | None) -> str:
    """Classify a module origin without importing a second runtime."""
    if not path:
        return "missing"
    if any(path.endswith(suffix) for suffix in importlib.machinery.EXTENSION_SUFFIXES):
        return "cython/native-extension"
    if path.endswith(".py"):
        return "python-source"
    return "unknown"


def _verify_serial_features(mode: str, serial_module) -> None:
    """Probe standalone serial cores, never an operator emulator or save.

    Version and revision markers alone cannot distinguish older working
    snapshots of the fork. These small ROM-free probes check required behavior.
    """
    def require(condition, detail):
        if not condition:
            raise SystemExit(f"PyBoy {mode} unsupported runtime: {detail}")

    for name, expected in (
        ("CYCLES_PER_EDGE_DMG", 512),
        ("CYCLES_PER_BYTE_DMG", 4096),
        ("CYCLES_8192HZ", 512),
    ):
        require(getattr(serial_module, name, None) == expected,
                f"serial {name} must be {expected}")
    serial = serial_module.Serial(False)
    require(callable(getattr(serial, "check_error", None)), "serial check_error API is missing")
    require(hasattr(serial, "backend_failed"), "serial backend_failed state is missing")
    require(not serial.backend_failed, "fresh serial core is already failed")
    error_type = getattr(serial_module, "SerialBackendError", None)
    require(isinstance(error_type, type) and issubclass(error_type, Exception),
            "SerialBackendError exception is missing")
    calls = []

    class RecordingBackend:
        def on_edge(self, bit, role):
            calls.append((bit, role))
            return 1

    serial.backend = RecordingBackend()
    serial.set_SB(0x80)
    serial.set_SC(0x81)
    require(serial.tick(511) is False and not calls, "serial clock shifts before 512 T-cycles")
    require(serial.tick(512) is False and calls == [(1, 1)],
            "serial first bit does not occur at 512 T-cycles")
    serial.check_error()

    failing = serial_module.Serial(False)
    failure = RuntimeError("bootstrap serial backend fault probe")
    failures = []

    class FailingBackend:
        def on_edge(self, bit, role):
            failures.append((bit, role))
            raise failure

    failing.backend = FailingBackend()
    failing.set_SB(0xA5)
    failing.set_SC(0x81)
    before = (failing._bits_remaining, failing._shift_register, failing.SB, failing.SC)
    require(failing.tick(512) is False, "failed serial edge generated an IRQ")
    require(failing.backend_failed, "serial backend exception was not latched")
    require((failing._bits_remaining, failing._shift_register, failing.SB, failing.SC) == before,
            "failed serial edge advanced transfer state")
    for _ in range(2):
        try:
            failing.check_error()
        except error_type as exc:
            require(exc.__cause__ is failure, "serial fault lost its original cause")
        else:
            require(False, "serial check_error did not raise the latched fault")
    require(failing.tick(4096) is False and failures == [(1, 1)],
            "failed serial core retried the backend or generated an IRQ")
    require((failing._bits_remaining, failing._shift_register, failing.SB, failing.SC) == before,
            "failed serial core mutated transfer state on a later tick")


def _verify_owner_clock_features(mode: str, pyboy_module, serial_module) -> None:
    """Bounded authored CGB instructions; never open BYO assets or saves."""
    from pyboy.utils import PyBoyAssertException

    def require(condition, detail):
        if not condition:
            raise SystemExit(f"PyBoy {mode} unsupported runtime: {detail}")

    # Original JP/header/NOP bytes, not a commercial ROM or derived fixture.
    cartridge = bytearray(32768)
    cartridge[0x100:0x103] = b"\xc3\x50\x01"
    cartridge[0x143] = 0x80
    cartridge[0x14D] = (-sum(cartridge[0x134:0x14D]) - 25) & 255
    with tempfile.TemporaryDirectory(prefix="pokered-bootstrap-") as temporary:
        path = Path(temporary) / "authored-cgb-probe.gb"
        path.write_bytes(cartridge)
        emulator = pyboy_module.PyBoy(str(path), window="null", sound_emulated=False)
        try:
            emulator.set_emulation_speed(0)
            emulator.memory[0xFF50] = 1
            emulator.register_file.PC = 0x150

            def clock():
                value = emulator.mb.get_physical_clock()
                require(isinstance(value, tuple) and len(value) == 2
                        and all(type(item) is int and item >= 0 for item in value),
                        "get_physical_clock must return nonnegative (generation, time) integers")
                return value

            def instruction(opcodes):
                emulator.memory[0, 0x150:0x150 + len(opcodes)] = opcodes
                emulator.register_file.PC = 0x150
                emulator.mb.breakpoint_singlestep = True
                emulator.mb.lcd.frame_done = False
                emulator.mb.tick()

            saved = io.BytesIO()
            emulator.save_state(saved)
            generation, start = clock()
            for opcodes, elapsed in (([0], 8), ([0x10, 0], 12), ([0], 16),
                                     ([0x10, 0], 24), ([0], 32)):
                # KEY1 is writable; rewriting it during double speed must not
                # change the physical rate before the next actual STOP.
                if opcodes[0] == 0x10 or elapsed == 16:
                    emulator.memory[0xFF4D] = 1
                instruction(opcodes)
                require(clock() == (generation, start + elapsed),
                        "physical clock does not account normal/double STOP boundaries")
            before = clock()
            saved.seek(0)
            emulator.load_state(saved)
            require(clock() == (before[0] + 1, before[1]),
                    "state load must change generation without rewinding physical time")
            instruction([0])
            require(clock() == (before[0] + 1, before[1] + 8),
                    "state load did not restore normal-speed physical accounting")
            before = clock()
            empty_load_failed = False
            try:
                emulator.load_state(io.BytesIO(b""))
            except PyBoyAssertException:
                empty_load_failed = True
            require(empty_load_failed, "empty state load unexpectedly succeeded")
            try:
                clock()
            except RuntimeError as exc:
                require("load is incomplete" in str(exc), "incomplete load lacks its clock fault")
            else:
                require(False, "incomplete load left physical clock available")
            saved.seek(0)
            emulator.load_state(saved)
            require(clock() == (before[0] + 2, before[1]),
                    "successful reload did not recover the incomplete-load generation")

            serial = emulator.mb.serial
            serial.set_SB(0xA5)
            serial.set_SC(0)
            emulator.register_file.A = 0x2A
            before = clock()
            owner_thread = threading.get_ident()
            observed = []

            def pump(event):
                require(isinstance(event, tuple) and len(event) >= 6
                        and event[1] == 1 and event[4] == 0xFF01,
                        "owner pump did not observe the serial MMIO read")
                require(threading.get_ident() == owner_thread
                        and emulator.register_file.PC == 0x150
                        and emulator.register_file.A == 0x2A and serial.SB == 0xA5,
                        "owner pump did not preserve owner-thread precommit state")
                require(clock() == clock() == (before[0], before[1] + 8),
                        "owner pump physical clock is stale or double-counted")
                try:
                    emulator.mb.tick()
                except RuntimeError as exc:
                    require("recursive CPU" in str(exc), "owner pump recursion guard is missing")
                else:
                    require(False, "owner pump allowed recursive CPU execution")
                observed.append(event)

            serial.set_owner_pump(pump)
            instruction([0xF0, 1])
            serial.set_owner_pump(None)
            require(len(observed) == 1 and emulator.register_file.A == 0xA5
                    and emulator.register_file.PC == 0x152
                    and clock() == (before[0], before[1] + 24),
                    "owner pump did not resume the original read exactly once")

            failure = RuntimeError("bootstrap owner pump fault probe")

            def failing_pump(_event):
                raise failure

            serial.set_owner_pump(failing_pump)
            emulator.register_file.A = 0x2A
            try:
                instruction([0xE0, 1])
            except serial_module.SerialBackendError as exc:
                require(exc.__cause__ is failure, "owner pump fault lost its cause")
            else:
                require(False, "owner pump fault did not reach the owner boundary")
            require(serial.backend_failed and not serial.owner_pump_active and serial.SB == 0xA5,
                    "owner pump fault committed a serial write or lost its latch")
            try:
                serial.check_error()
            except serial_module.SerialBackendError as exc:
                require(exc.__cause__ is failure, "owner pump fault latch lost its cause")
            else:
                require(False, "owner pump fault latch cleared unexpectedly")
        finally:
            emulator.stop(save=False)


def _verify_owner_poll_features(mode: str, pyboy_module, serial_module) -> None:
    """Require exclusive bindings and real pre-CPU/HALT owner polling."""
    def require(condition, detail):
        if not condition:
            raise SystemExit(f"PyBoy {mode} unsupported runtime: {detail}")

    def rejected(operation, detail):
        try:
            operation()
        except RuntimeError:
            return
        require(False, detail)

    core = serial_module.Serial(False)
    core.set_SB(0xA5)
    core.set_SC(0x81)
    legacy, claimed = [], []
    core.set_owner_pump(legacy.append)
    rejected(lambda: core.claim_owner_pump(claimed.append, poll=True),
             "owner claim replaced an existing callback")
    core.tick(512)
    core.check_error()
    require(len(legacy) == 1 and not claimed, "rejected claim lost the existing callback")
    core.set_owner_pump(None)

    def claimed_callback(event):
        require(core.owner_pump_active, "claimed callback lacks its active boundary")
        rejected(lambda: core.release_owner_pump(token), "active callback released its own claim")
        rejected(lambda: core.set_owner_pump(None), "active callback replaced its binding")
        rejected(lambda: core.claim_owner_pump(legacy.append), "active callback acquired another claim")
        claimed.append(event)

    token = core.claim_owner_pump(claimed_callback, poll=True)
    require(token is not None and core.owner_poll_enabled, "owner claim did not enable requested polling")
    for callback in (None, legacy.append):
        rejected(lambda callback=callback: core.set_owner_pump(callback),
                 "setter replaced an exclusively claimed callback")
    rejected(lambda: core.claim_owner_pump(legacy.append), "second claim replaced its owner")
    for invalid in (None, object()):
        rejected(lambda invalid=invalid: core.release_owner_pump(invalid),
                 "wrong token released an owner claim")
    thread_results = []

    def off_thread_release():
        try:
            core.release_owner_pump(token)
        except (RuntimeError, TypeError, ValueError) as exc:
            thread_results.append(exc)
        else:
            thread_results.append(None)

    worker = threading.Thread(target=off_thread_release, daemon=True)
    worker.start()
    worker.join(2)
    require(not worker.is_alive() and len(thread_results) == 1
            and isinstance(thread_results[0], RuntimeError), "claim release did not reject a foreign thread")
    core.tick(1024)
    core.check_error()
    require(len(claimed) == 1 and len(legacy) == 1 and core.owner_poll_enabled,
            "rejected binding operations changed the claimed callback")
    core.release_owner_pump(token)
    require(not core.owner_poll_enabled, "claim release left owner polling enabled")
    core.tick(1536)
    core.check_error()
    require(len(claimed) == 1, "claim release left its callback installed")
    replacement = core.claim_owner_pump(legacy.append)
    require(replacement is not None and replacement is not token and not core.owner_poll_enabled,
            "fresh default claim reused a token or enabled unsolicited polling")
    rejected(lambda: core.release_owner_pump(token), "stale token released a newer claim")
    core.tick(2048)
    core.check_error()
    require(len(legacy) == 2, "stale-token rejection lost the newer callback")
    core.release_owner_pump(replacement)

    failed = serial_module.Serial(False)
    failed.set_SB(0xA5)
    failed.set_SC(0x81)
    cause = RuntimeError("bootstrap claimed-pump fault probe")

    def fault(_event):
        raise cause

    fault_token = failed.claim_owner_pump(fault, poll=True)
    failed.tick(512)
    failed.release_owner_pump(fault_token)
    require(failed.backend_failed and not failed.owner_poll_enabled and not failed.owner_pump_active,
            "fault-safe claim release cleared the error or retained its binding")
    for operation in (failed.check_error, lambda: failed.claim_owner_pump(legacy.append)):
        try:
            operation()
        except serial_module.SerialBackendError as exc:
            require(exc.__cause__ is cause, "claim release lost the original latched fault cause")
        else:
            require(False, "released failed core admitted continuation")

    cartridge = bytearray(32768)
    cartridge[0x100:0x103] = b"\xc3\x50\x01"
    cartridge[0x143] = 0x80
    cartridge[0x14D] = (-sum(cartridge[0x134:0x14D]) - 25) & 255
    with tempfile.TemporaryDirectory(prefix="pokered-owner-poll-") as temporary:
        path = Path(temporary) / "authored-poll-probe.gb"
        path.write_bytes(cartridge)
        emulator = pyboy_module.PyBoy(str(path), window="null", sound_emulated=False)
        try:
            emulator.set_emulation_speed(0)
            emulator.memory[0xFF50] = 1
            emulator.memory[0xFFFF] = emulator.memory[0xFF0F] = 0
            emulator.memory[0, 0x150:0x152] = [0, 0x76]  # NOP, then actual HALT.
            emulator.register_file.PC, emulator.register_file.A = 0x150, 0x2A
            serial = emulator.mb.serial
            polls = []
            owner_thread = threading.get_ident()

            def poll(event):
                require(isinstance(event, tuple) and len(event) == 12
                        and event[1] == 4 and event[4:6] == (-1, -1),
                        "owner poll did not publish a kind-4 pre-CPU boundary")
                require(threading.get_ident() == owner_thread and serial.owner_pump_active
                        and emulator.register_file.PC == expected_pc and emulator.register_file.A == 0x2A
                        and emulator.mb.get_physical_clock() == before,
                        "owner poll ran after CPU/HALT progress or off its owner thread")
                polls.append(event)

            def cpu_slice():
                emulator.mb.breakpoint_singlestep = True
                emulator.mb.lcd.frame_done = False
                emulator.mb.tick()

            poll_token = serial.claim_owner_pump(poll, poll=True)
            for index, expected_pc in enumerate((0x150, 0x151, 0x151), 1):
                before = emulator.mb.get_physical_clock()
                cpu_slice()
                require(len(polls) == index and emulator.register_file.PC == 0x151
                        and emulator.mb.get_physical_clock() == (before[0], before[1] + 8),
                        "owner poll did not precede each original NOP/HALT slice exactly once")
            serial.release_owner_pump(poll_token)
            cpu_slice()
            require(len(polls) == 3 and not serial.owner_poll_enabled,
                    "released poll callback remained installed")
            default_token = serial.claim_owner_pump(polls.append)
            cpu_slice()
            require(len(polls) == 3 and not serial.owner_poll_enabled,
                    "default owner claim emitted unsolicited CPU polls")
            serial.release_owner_pump(default_token)
        finally:
            emulator.stop(save=False)


def _check_contract(mode: str) -> None:
    """Validate the selected source or Cython runtime import contract."""
    if mode not in {"source", "cython"}:
        raise ValueError(f"unsupported runtime mode: {mode!r}")
    _validate_source()
    try:
        import pyboy
        from pyboy.core.serial import Serial, SerialCore
        from pyboy.link import LinkSession  # noqa: F401

        modules = {
            name: importlib.import_module(name)
            for name in ("pokered_harness", "pyboy", "pyboy.link", *COMPILED_MODULES)
        }
    except Exception as exc:
        raise SystemExit(f"PyBoy {mode} contract failed: {exc}") from exc
    origins = {name: getattr(module, "__file__", None) for name, module in modules.items()}
    if not all(origins.values()):
        raise SystemExit(f"PyBoy {mode} contract failed: a required module has no origin")
    expected_kind = "python-source" if mode == "source" else "cython/native-extension"
    for name in COMPILED_MODULES:
        actual = _module_kind(origins[name])
        if actual != expected_kind:
            raise SystemExit(
                f"PyBoy {mode} contract failed: {name} is {actual}, "
                f"expected {expected_kind}; use a separate environment for each mode"
            )
    if mode == "source" and SerialCore is not Serial:
        raise SystemExit("PyBoy source contract failed: SerialCore is not Serial")
    if getattr(pyboy, "__version__", None) != "2.7.0":
        raise SystemExit(
            f"PyBoy {mode} contract failed: expected version 2.7.0, "
            f"got {getattr(pyboy, '__version__', None)!r}"
        )
    revision = getattr(pyboy, "__pokered_harness_revision__", None)
    if revision != EXPECTED_REVISION:
        raise SystemExit(
            f"PyBoy {mode} contract failed: expected revision {EXPECTED_REVISION}, got {revision!r}"
        )
    serial = Serial(False)
    for name in ("set_SB", "set_SC", "apply_external_edge", "tick", "peek_out_bit", "set_owner_pump",
                 "claim_owner_pump", "release_owner_pump"):
        if not callable(getattr(serial, name, None)):
            raise SystemExit(f"PyBoy {mode} contract failed: serial API {name} is missing")
    if not hasattr(serial, "backend"):
        raise SystemExit(f"PyBoy {mode} contract failed: serial backend is inaccessible")
    motherboard = getattr(modules["pyboy.core.mb"], "Motherboard", None)
    if not callable(getattr(motherboard, "get_physical_clock", None)):
        raise SystemExit(f"PyBoy {mode} contract failed: motherboard API get_physical_clock is missing")
    owner = _verify_ownership(mode, origins)
    try:
        _verify_serial_features(mode, modules["pyboy.core.serial"])
    except Exception as exc:
        raise SystemExit(f"PyBoy {mode} unsupported runtime: serial feature probe failed: {exc}") from exc
    try:
        _verify_owner_clock_features(mode, modules["pyboy"], modules["pyboy.core.serial"])
    except Exception as exc:
        raise SystemExit(f"PyBoy {mode} unsupported runtime: owner/physical-clock probe failed: {exc}") from exc
    try:
        _verify_owner_poll_features(mode, modules["pyboy"], modules["pyboy.core.serial"])
    except Exception as exc:
        raise SystemExit(f"PyBoy {mode} unsupported runtime: owner claim/poll probe failed: {exc}") from exc
    print(
        f"PyBoy {mode} contract OK: revision={EXPECTED_REVISION} "
        f"serial={Serial.__name__} kind={expected_kind} owner={owner} "
        "features=normal-clock-512T,latched-backend-error,serial-owner-pump,physical-clock-generation,"
        "exclusive-owner-pump,pre-cpu-owner-poll "
        f"path={origins['pyboy']}"
    )


def _run_bounded(command: list[str], *, env: dict[str, str], timeout: float) -> int:
    """Bound pip/build descendants as well as the immediate subprocess."""
    options = (
        {"start_new_session": True}
        if os.name != "nt"
        else {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP}
    )
    try:
        process = subprocess.Popen(command, cwd=ROOT, env=env, **options)
    except OSError as exc:
        print(f"PyBoy bootstrap could not start subprocess: {exc}", file=sys.stderr)
        return 1
    try:
        return process.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        print(f"PyBoy bootstrap subprocess exceeded {timeout:g}s", file=sys.stderr)
        try:
            if os.name == "nt":
                subprocess.run(
                    ["taskkill", "/PID", str(process.pid), "/T", "/F"],
                    check=False,
                    timeout=10,
                    capture_output=True,
                )
            else:
                os.killpg(process.pid, signal.SIGKILL)
        except (OSError, subprocess.TimeoutExpired) as exc:
            print(f"PyBoy bootstrap tree cleanup failed: {exc}", file=sys.stderr)
        try:
            process.kill()
            process.wait(timeout=10)
        except (OSError, subprocess.TimeoutExpired) as exc:
            print(f"PyBoy bootstrap process cleanup failed: {exc}", file=sys.stderr)
        return 124


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--mode",
        choices=("source", "cython"),
        default="source",
        help="runtime build mode (default: source)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate the vendored source/import contract without installing",
    )
    parser.add_argument(
        "--install-timeout",
        type=float,
        default=600,
        help="maximum install/build seconds (default: 600)",
    )
    parser.add_argument(
        "--check-timeout",
        type=float,
        default=30,
        help="maximum seconds per dependency/contract check (default: 30; native install runs both)",
    )
    parser.add_argument("--probe-contract", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    for value in (args.install_timeout, args.check_timeout):
        if not math.isfinite(value) or value <= 0:
            parser.error("timeouts must be finite and positive")

    _validate_source()
    if args.probe_contract:
        _check_contract(args.mode)
        return 0
    env = os.environ.copy()
    if args.mode == "source":
        env["PYBOY_NO_CYTHON"] = "1"
    else:
        env.pop("PYBOY_NO_CYTHON", None)

    check_command = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--mode",
        args.mode,
        "--probe-contract",
    ]
    if args.check:
        return _run_bounded(check_command, env=env, timeout=args.check_timeout)

    command = [
        sys.executable,
        "-m",
        "pip",
        "install",
        "--force-reinstall",
        "--no-deps",
    ]
    if args.mode == "cython":
        try:
            with _native_build_source() as staged:
                result = _run_bounded(
                    [*command, "--no-cache-dir", str(staged)], env=env, timeout=args.install_timeout
                )
        except (OSError, ValueError) as exc:
            print(f"PyBoy native source staging failed: {exc}", file=sys.stderr)
            return 1
        if result:
            return result
        result = _run_bounded(
            [sys.executable, "-m", "pip", "check"], env=env, timeout=args.check_timeout
        )
    else:
        result = _run_bounded([*command, str(ROOT)], env=env, timeout=args.install_timeout)
    if result:
        return result
    return _run_bounded(check_command, env=env, timeout=args.check_timeout)


if __name__ == "__main__":
    raise SystemExit(main())
